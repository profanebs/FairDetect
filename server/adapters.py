# -*- coding: utf-8 -*-
"""Model adapters for FairDetect.

An adapter turns a list of text windows into AI probabilities in [0, 1].

Supported adapters
------------------
hf      A local Hugging Face sequence-classification checkpoint. The model must
        be a directory containing config.json, tokenizer files and weights.
        Binary classifiers are scored with softmax; single-logit models with
        sigmoid. The AI label can be set explicitly or detected from id2label.

openai  Any OpenAI-compatible local chat endpoint (Ollama, LM Studio,
        llama.cpp server, vLLM, ...). One request per window. The model is
        asked to return JSON: {"ai_probability": 0.0 .. 1.0}.
        This path is slow and uncalibrated; use it to attach a local LLM,
        not as a drop-in replacement for a trained classifier.

http    A tiny local scoring service. FairDetect POSTs {"text": "..."} and
        expects a JSON object containing one of: score, ai_probability,
        probability. Use this to bridge ONNX, a custom model server, etc.

All network calls ignore system proxy settings so that localhost endpoints
work on machines with a corporate proxy configured.
"""
from __future__ import annotations

import json
import os
import re
import urllib.error
import urllib.request
from pathlib import Path

DEFAULT_PROMPT = (
    "You are an AI-text detector. Estimate the probability that the passage below "
    "was generated by a large language model rather than written by a human. "
    "Answer with JSON only, exactly one object: {\"ai_probability\": <number from 0 to 1>}.\n\n"
    "PASSAGE:\n<<<\n{text}\n>>>"
)

_PROB_KEYS = ("ai_probability", "ai_prob", "probability", "score", "p")


class AdapterError(RuntimeError):
    pass


def _expand(value):
    """Expand ${ENV_VAR} references in config strings."""
    if isinstance(value, str):
        return re.sub(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}",
                      lambda m: os.environ.get(m.group(1), ""), value)
    if isinstance(value, dict):
        return {k: _expand(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_expand(v) for v in value]
    return value


def _resolve(root, p):
    path = Path(str(p)).expanduser()
    if not path.is_absolute():
        path = (root / path).resolve()
    return path


def _clamp01(x):
    return max(0.0, min(1.0, float(x)))


def _parse_probability(text):
    raw = str(text)
    match = re.search(r"\{[^{}]*\}", raw, re.S)
    if match:
        try:
            obj = json.loads(match.group(0))
        except Exception:
            obj = None
        if isinstance(obj, dict):
            for key in _PROB_KEYS:
                if key in obj:
                    try:
                        return _clamp01(obj[key])
                    except Exception:
                        pass
    pct = re.search(r"(\d+(?:\.\d+)?)\s*%", raw)
    if pct:
        return _clamp01(float(pct.group(1)) / 100.0)
    num = re.search(r"(?<![\d.])(?:0(?:\.\d+)?|1(?:\.0+)?)(?![\d.])", raw)
    if num:
        return _clamp01(float(num.group(0)))
    raise AdapterError("cannot parse ai_probability from model output: %r" % raw[:200])


class HFClassifierAdapter:
    kind = "hf"

    def __init__(self, spec, root):
        self.spec = spec
        self.path = _resolve(root, spec.get("path", ""))
        self.max_length = int(spec.get("max_length", 256))
        self.batch_size = int(spec.get("batch_size", 32))
        self.ai_label_index = spec.get("ai_label_index", "auto")
        self.device_pref = str(spec.get("device", "auto")).lower()
        self._loaded = None

    def available(self):
        if not self.path.is_dir():
            return False
        if not (self.path / "config.json").is_file():
            return False
        markers = ("model.safetensors", "pytorch_model.bin",
                   "model.safetensors.index.json", "pytorch_model.bin.index.json")
        return any((self.path / name).is_file() for name in markers)

    def status(self):
        if not self.path.exists():
            return "missing: %s" % self.path
        if not self.available():
            return "not a Hugging Face sequence-classification directory: %s" % self.path
        return "ok: %s" % self.path

    def _load(self):
        if self._loaded is not None:
            return self._loaded
        try:
            import torch
            from transformers import AutoTokenizer, AutoModelForSequenceClassification
        except Exception as e:
            raise AdapterError("torch/transformers not installed: %s" % e)
        device = self.device_pref
        if device in ("", "auto"):
            device = "cuda" if torch.cuda.is_available() else "cpu"
        try:
            tok = AutoTokenizer.from_pretrained(str(self.path), local_files_only=True)
            model = AutoModelForSequenceClassification.from_pretrained(
                str(self.path), local_files_only=True)
            model = model.float().to(device).eval()
        except Exception as e:
            raise AdapterError("cannot load %s: %s" % (self.path, e))
        if self.ai_label_index == "auto" or self.ai_label_index is None:
            labels = getattr(model.config, "id2label", {}) or {}
            picked = None
            for idx, label in labels.items():
                low = str(label).lower()
                if any(token in low for token in ("ai", "machine", "fake", "generated", "chatgpt")):
                    picked = int(idx)
                    break
            self.ai_label_index = 1 if picked is None else picked
        else:
            self.ai_label_index = int(self.ai_label_index)
        self._loaded = (torch, tok, model, device)
        return self._loaded

    def score(self, texts):
        torch, tok, model, device = self._load()
        out = []
        with torch.no_grad():
            for i in range(0, len(texts), self.batch_size):
                batch = list(texts[i:i + self.batch_size])
                enc = tok(batch, truncation=True, max_length=self.max_length,
                          padding=True, return_tensors="pt")
                enc = {k: v.to(device) for k, v in enc.items()}
                if device.startswith("cuda"):
                    with torch.autocast("cuda", dtype=torch.float16):
                        logits = model(**enc).logits
                else:
                    logits = model(**enc).logits
                logits = logits.float()
                if logits.ndim == 1:
                    logits = logits.unsqueeze(0)
                if logits.shape[-1] == 1:
                    probs = torch.sigmoid(logits[:, 0])
                else:
                    if self.ai_label_index >= logits.shape[-1]:
                        raise AdapterError(
                            "ai_label_index %d out of range for %d labels"
                            % (self.ai_label_index, logits.shape[-1]))
                    probs = torch.softmax(logits, dim=-1)[:, self.ai_label_index]
                out.extend(float(x) for x in probs.cpu().tolist())
        return out


class OpenAICompatibleAdapter:
    kind = "openai"

    def __init__(self, spec, root):
        base = str(_expand(spec.get("base_url") or "http://127.0.0.1:11434/v1")).rstrip("/")
        self.url = base if base.endswith("/chat/completions") else base + "/chat/completions"
        self.model = str(spec.get("model") or "").strip()
        if not self.model:
            raise AdapterError("openai adapter needs a model name")
        self.api_key = str(_expand(spec.get("api_key") or "")).strip()
        env_name = str(spec.get("api_key_env") or "").strip()
        if not self.api_key and env_name:
            self.api_key = os.environ.get(env_name, "").strip()
        self.timeout = int(spec.get("timeout", 180))
        self.temperature = float(spec.get("temperature", 0))
        self.max_tokens = int(spec.get("max_tokens", 64))
        self.prompt = str(spec.get("prompt") or DEFAULT_PROMPT)
        self.opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))

    def available(self):
        return True

    def status(self):
        return "configured: %s (%s); connectivity is checked on first score" % (self.url, self.model)

    def _score_one(self, text):
        prompt = self.prompt.replace("{text}", str(text))
        body = {
            "model": self.model,
            "messages": [{"role": "user", "content": prompt}],
            "temperature": self.temperature,
            "max_tokens": self.max_tokens,
            "stream": False,
        }
        headers = {"Content-Type": "application/json"}
        if self.api_key:
            headers["Authorization"] = "Bearer " + self.api_key
        req = urllib.request.Request(self.url, data=json.dumps(body).encode("utf-8"),
                                     headers=headers, method="POST")
        try:
            with self.opener.open(req, timeout=self.timeout) as r:
                data = json.loads(r.read().decode("utf-8"))
        except urllib.error.HTTPError as e:
            detail = e.read().decode("utf-8", "replace")[:500]
            raise AdapterError("HTTP %s from %s: %s" % (e.code, self.url, detail))
        except Exception as e:
            raise AdapterError("cannot reach %s: %s" % (self.url, e))
        try:
            content = data["choices"][0]["message"]["content"]
        except Exception:
            raise AdapterError("unexpected response from %s: %r" % (self.url, str(data)[:300]))
        return _parse_probability(content)

    def score(self, texts):
        return [self._score_one(t) for t in texts]


class HTTPAdapter:
    kind = "http"

    def __init__(self, spec, root):
        self.url = str(_expand(spec.get("url") or "")).strip()
        if not self.url:
            raise AdapterError("http adapter needs a url")
        self.timeout = int(spec.get("timeout", 120))
        self.field = str(spec.get("field") or "score")
        self.headers = _expand(spec.get("headers") or {})
        self.opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))

    def available(self):
        return True

    def status(self):
        return "configured: %s; connectivity is checked on first score" % self.url

    def score(self, texts):
        out = []
        for text in texts:
            body = json.dumps({"text": str(text)}).encode("utf-8")
            headers = {"Content-Type": "application/json"}
            headers.update({str(k): str(v) for k, v in self.headers.items()})
            req = urllib.request.Request(self.url, data=body, headers=headers, method="POST")
            try:
                with self.opener.open(req, timeout=self.timeout) as r:
                    data = json.loads(r.read().decode("utf-8"))
            except urllib.error.HTTPError as e:
                detail = e.read().decode("utf-8", "replace")[:500]
                raise AdapterError("HTTP %s from %s: %s" % (e.code, self.url, detail))
            except Exception as e:
                raise AdapterError("cannot reach %s: %s" % (self.url, e))
            if not isinstance(data, dict):
                raise AdapterError("expected a JSON object from %s, got %r" % (self.url, str(data)[:200]))
            value = data.get(self.field)
            if value is None:
                for key in _PROB_KEYS:
                    if key in data:
                        value = data[key]
                        break
            if value is None:
                raise AdapterError("response from %s has no %r field: %r"
                                   % (self.url, self.field, str(data)[:200]))
            out.append(_clamp01(value))
        return out


def build_adapter(spec, root):
    kind = str(spec.get("adapter") or "hf").lower()
    if kind in ("hf", "hf_classifier", "transformer", "deberta"):
        return HFClassifierAdapter(spec, root)
    if kind in ("openai", "openai_compatible", "llm", "ollama"):
        return OpenAICompatibleAdapter(spec, root)
    if kind in ("http", "http_score", "service"):
        return HTTPAdapter(spec, root)
    raise AdapterError("unknown adapter type: %s" % kind)
